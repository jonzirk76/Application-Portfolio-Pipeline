import { test, expect } from '@playwright/test';
import path from 'node:path';

test('enclosure geometry, stale drawing issue, regeneration and source export', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/enclosure.html');
  await expect(page.locator('#detail h3')).toHaveText('F-01');
  await expect(page.locator('#metrics .metric').nth(1).locator('strong')).toHaveText('3');
  await expect(page.locator('#viewer-status')).toContainText('Revised enclosure loaded', { timeout: 60000 });
  await expect(page.locator('#model-container')).toHaveAttribute('data-selected-guid', /.+/);
  await expect(page.locator('#drawing-status')).toHaveText('Stale drawing');
  await expect.poll(() => page.locator('#drawing').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  const originalDrawing = await page.locator('#drawing').getAttribute('src');
  await page.screenshot({ path: 'test-results/enclosure-stale.png', fullPage: true });
  await page.getByRole('button', { name: 'B · Revised', exact: true }).click();
  const revisedId = await page.locator('#model-container').getAttribute('data-revision');
  await page.getByRole('button', { name: 'A · Baseline', exact: true }).click();
  await expect(page.locator('#viewer-status')).toContainText('Baseline enclosure loaded');
  expect(await page.locator('#model-container').getAttribute('data-revision')).not.toBe(revisedId);
  await page.getByRole('button', { name: 'HSS-02', exact: true }).click();
  await expect(page.locator('#detail h3')).toHaveText('HSS-02');
  await expect(page.locator('#detail')).toContainText('0.25');
  await page.getByRole('button', { name: 'Generate current package' }).click();
  await expect(page.locator('#metrics .metric').nth(1).locator('strong')).toHaveText('0');
  await expect(page.locator('#findings')).toContainText('No detail discrepancies detected');
  expect(await page.locator('#drawing').getAttribute('src')).not.toBe(originalDrawing);
  await expect(page.locator('#drawing-status')).toHaveText('Current detail inputs');
  await page.getByLabel('Drawing', { exact: true }).selectOption('S-501');
  await expect(page.locator('#drawing')).toHaveAttribute('src', /S-501.svg$/);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download package', exact: false }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('enclosure-drawing-package.zip');
  await download.saveAs('test-results/enclosure-package.zip');
  await page.reload();
  expect(await page.locator('#package option').count()).toBeGreaterThanOrEqual(2);
  expect(errors).toEqual([]);
});

test('alignment control, real IFC upload and mobile drawings', async ({ page }) => {
  await page.goto('/enclosure.html');
  await expect(page.locator('#detail h3')).toHaveText('F-01');
  await page.getByRole('button', { name: 'Unchanged control', exact: true }).click();
  await expect(page.locator('#metrics .metric').nth(0).locator('strong')).toHaveText('0');
  await expect(page.locator('#metrics .metric').nth(1).locator('strong')).toHaveText('0');
  await page.getByRole('button', { name: 'Post alignment example' }).click();
  await expect(page.locator('#findings')).toContainText('4.000 in off footing center');
  await expect(page.locator('#metrics .metric').nth(2).locator('strong')).toHaveText('1');
  await page.getByRole('button', { name: 'Generate current package' }).click();
  await expect(page.locator('#metrics .metric').nth(1).locator('strong')).toHaveText('0');
  await expect(page.locator('#metrics .metric').nth(2).locator('strong')).toHaveText('1');
  await page.getByLabel('Import revised IFC', { exact: true }).setInputFiles(path.resolve('../fixtures/enclosure/revised.ifc'));
  await expect(page.locator('#metrics .metric').nth(2).locator('strong')).toHaveText('0');
  await page.getByLabel('Import revised IFC', { exact: true }).setInputFiles({ name: 'bad.ifc', mimeType: 'text/plain', buffer: Buffer.from('not IFC') });
  await expect(page.locator('#message')).toContainText('Unable to read IFC');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Enclosure foundation details', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/enclosure-mobile.png', fullPage: true });
});
